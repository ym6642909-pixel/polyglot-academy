/* Polyglot Academy service worker — polyglot-v1
   Cache-first for versioned assets (…?v=N, treated as immutable per version),
   network-first for everything else (pages, manifest) with cache fallback.
   Same-origin GET requests only; API calls and cross-origin traffic bypass. */
const CACHE = 'polyglot-v1'

self.addEventListener('install', () => {
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  )
})

self.addEventListener('fetch', (event) => {
  const req = event.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (url.origin !== self.location.origin) return

  // Versioned static assets (?v=N): cache first, fall back to network.
  if (url.searchParams.has('v') || /\.(png|svg|woff2?)$/.test(url.pathname)) {
    event.respondWith(
      caches.match(req).then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            const copy = res.clone()
            caches.open(CACHE).then((c) => c.put(req, copy))
            return res
          })
      )
    )
    return
  }

  // Navigations, manifest, sw.js: network first, cache as offline fallback.
  event.respondWith(
    fetch(req)
      .then((res) => {
        const copy = res.clone()
        caches.open(CACHE).then((c) => c.put(req, copy))
        return res
      })
      .catch(() => caches.match(req))
  )
})
